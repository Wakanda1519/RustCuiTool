const DICTS: Record<Lang, Record<TKey, string>> = { en, ru };

/**
 * Translate a key. Missing values fall back to English and then to the key.
 * `{name}` placeholders are replaced from `vars`.
 */
export function translate(lang: Lang, key: TKey, vars?: Record<string, string | number>): string {
  const template = DICTS[lang]?.[key] ?? en[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in vars ? String(vars[name]) : match,
  );
}

/** Translate with a dynamic key (used by validation helpers). */
export function translateDynamic(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  return translate(lang, key as TKey, vars);
}
